from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
from schemas.campaign import CampaignInput, PredictionInterval, RiskFlag, ImprovementSuggestion

class WhatIfRequest(BaseModel):
    baseline_campaign: CampaignInput
    modified_parameter: str = Field(..., description="Parameter being adjusted (budget, channel, campaign_duration, etc.)")
    modified_value: Any = Field(..., description="The candidate value tested")
    modified_campaign: Optional[CampaignInput] = Field(None, description="Full modified campaign if pre-built")

class MetricComparison(BaseModel):
    metric_name: str
    baseline_value: float
    scenario_value: float
    delta_absolute: float
    delta_percentage: float
    is_positive: bool
    baseline_interval: PredictionInterval
    scenario_interval: PredictionInterval

class WhatIfResponse(BaseModel):
    simulation_id: str
    parameter_changed: str
    original_value: Any
    new_value: Any
    reach_comparison: MetricComparison
    ctr_comparison: MetricComparison
    conversions_comparison: MetricComparison
    new_risks: List[RiskFlag]
    risk_summary_change: str
    gemini_scenario_explanation: str
    timestamp: str

# ----------------- AGENT 5 (Marketing Optimization Agent) CONTRACT -----------------

class Agent5EvaluationCandidate(BaseModel):
    candidate_id: str = Field(..., description="Unique ID of optimization candidate generated by Agent 5")
    campaign: CampaignInput

class Agent5EvaluationResult(BaseModel):
    candidate_id: str
    campaign_input_summary: Dict[str, Any]
    predicted_reach: PredictionInterval
    predicted_ctr: PredictionInterval
    predicted_conversions: PredictionInterval
    risk_flags: List[RiskFlag]
    improvement_suggestions: List[ImprovementSuggestion]
    model_metadata: Dict[str, Any]
    prediction_timestamp: str

class Agent5BatchEvaluationRequest(BaseModel):
    candidates: List[Agent5EvaluationCandidate]

class Agent5BatchEvaluationResponse(BaseModel):
    results: List[Agent5EvaluationResult]
    total_evaluated: int
    optimal_candidate_id: Optional[str] = None
